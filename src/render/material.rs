#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub(super) struct ShaderKey {
    pub kind: u8,
    pub cutoff: u8,
    pub cardinal: bool,
    pub per_face: bool,
    pub overlay: bool,
    pub lightmap: bool,
    pub wrap: bool,
    pub fog: bool,
    pub dissolve: bool,
    pub view_offset: i8,
    pub portal_layers: u8,
}
impl ShaderKey {
    pub fn constants(self) -> [(&'static str, f64); 11] {
        [
            ("source_kind", f64::from(self.kind)),
            ("source_cutoff", f64::from(self.cutoff) / 100.),
            ("source_cardinal", f64::from(u8::from(self.cardinal))),
            ("source_per_face", f64::from(u8::from(self.per_face))),
            ("source_overlay", f64::from(u8::from(self.overlay))),
            ("source_lightmap", f64::from(u8::from(self.lightmap))),
            ("source_wrap", f64::from(u8::from(self.wrap))),
            ("source_fog", f64::from(u8::from(self.fog))),
            ("source_dissolve", f64::from(u8::from(self.dissolve))),
            (
                "source_view_scale",
                1. - f64::from(self.view_offset) / 4096.,
            ),
            ("source_portal_layers", f64::from(self.portal_layers)),
        ]
    }
}
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub(super) struct Descriptor {
    pub shader: ShaderKey,
    pub blend: u8,
    pub depth: u8,
    pub write_depth: bool,
    pub cull: bool,
    pub bias: bool,
    pub color_write: bool,
    pub sort: bool,
    pub sort_key: u32,
}
impl Descriptor {
    pub fn raster_equivalent(self, other: Self) -> bool {
        self.shader == other.shader
            && self.blend == other.blend
            && self.depth == other.depth
            && self.write_depth == other.write_depth
            && self.cull == other.cull
            && self.bias == other.bias
            && self.color_write == other.color_write
    }
    pub fn blend_state(self) -> Option<wgpu::BlendState> {
        use wgpu::BlendFactor as F;
        let factors = match self.blend {
            0 => return None,
            1 => (
                F::SrcAlpha,
                F::OneMinusSrcAlpha,
                F::One,
                F::OneMinusSrcAlpha,
            ),
            2 => (F::One, F::One, F::One, F::One),
            3 => (F::Src, F::One, F::Zero, F::One),
            4 => (F::Dst, F::Src, F::One, F::Zero),
            5 => (F::SrcAlpha, F::One, F::SrcAlpha, F::One),
            _ => unreachable!(),
        };
        Some(wgpu::BlendState {
            color: wgpu::BlendComponent {
                src_factor: factors.0,
                dst_factor: factors.1,
                operation: wgpu::BlendOperation::Add,
            },
            alpha: wgpu::BlendComponent {
                src_factor: factors.2,
                dst_factor: factors.3,
                operation: wgpu::BlendOperation::Add,
            },
        })
    }
}
