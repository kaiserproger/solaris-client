pub(crate) fn atan2(mut y: f64, mut x: f64) -> f64 {
    let norm = x * x + y * y;
    if norm.is_nan() {
        return f64::NAN;
    }
    let negative_y = y < 0.;
    if negative_y {
        y = -y;
    }
    let negative_x = x < 0.;
    if negative_x {
        x = -x;
    }
    let swapped = y > x;
    if swapped {
        std::mem::swap(&mut x, &mut y);
    }
    let estimate = f64::from_bits(6910469410427058090u64.wrapping_sub(norm.to_bits() >> 1));
    let inverse = estimate * (1.5 - ((0.5 * norm) * estimate) * estimate);
    x *= inverse;
    y *= inverse;
    let bias = f64::from_bits(4805340802404319232);
    let indexed = bias + y;
    let i = indexed.to_bits() as u32 as usize;
    let sine = indexed - bias;
    let error = y * f64::from_bits(COS[i]) - x * sine;
    let correction = ((6. + error * error) * error) * (1. / 6.);
    let mut angle = f64::from_bits(ASIN[i]) + correction;
    if swapped {
        angle = std::f64::consts::FRAC_PI_2 - angle;
    }
    if negative_x {
        angle = std::f64::consts::PI - angle;
    }
    if negative_y {
        angle = -angle;
    }
    angle
}
pub(crate) fn id_hash(id: &WaypointId) -> u32 {
    match id {
        WaypointId::Uuid(bytes) => bytes.chunks_exact(4).fold(0, |hash, b| {
            hash ^ u32::from_be_bytes(b.try_into().unwrap())
        }),
        WaypointId::Named(name) => name.encode_utf16().fold(0u32, |hash, ch| {
            hash.wrapping_mul(31).wrapping_add(u32::from(ch))
        }),
    }
}
pub(crate) fn marker_color(id: &WaypointId) -> u32 {
    brightness(id_hash(id) | 0xff000000, 0.9)
}
pub(crate) fn brightness(color: u32, value: f32) -> u32 {
    let original = [
        ((color >> 16) & 255) as f32,
        ((color >> 8) & 255) as f32,
        (color & 255) as f32,
    ];
    let [r, g, b] = original;
    let max = r.max(g).max(b);
    let min = r.min(g).min(b);
    let delta = max - min;
    let saturation = if max != 0. { delta / max } else { 0. };
    let hue = if saturation == 0. {
        0.
    } else {
        let rr = (max - r) / delta;
        let gg = (max - g) / delta;
        let bb = (max - b) / delta;
        let mut h = if r == max {
            bb - gg
        } else if g == max {
            2. + rr - bb
        } else {
            4. + gg - rr
        };
        h /= 6.;
        if h < 0. {
            h += 1.;
        }
        h
    };
    let rgb = if saturation == 0. {
        [value; 3]
    } else {
        let sector = (hue - hue.floor()) * 6.;
        let fraction = sector - sector.floor();
        let p = value * (1. - saturation);
        let q = value * (1. - saturation * fraction);
        let t = value * (1. - saturation * (1. - fraction));
        match sector as i32 {
            0 => [value, t, p],
            1 => [q, value, p],
            2 => [p, value, t],
            3 => [p, q, value],
            4 => [t, p, value],
            5 => [value, p, q],
            _ => return color,
        }
    };
    let channel = |v: f32| ((v * 255. + 0.5).floor() as u32) & 255;
    (color & 0xff000000) | (channel(rgb[0]) << 16) | (channel(rgb[1]) << 8) | channel(rgb[2])
}
